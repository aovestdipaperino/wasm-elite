//! An original 8x8 bitmap font for ASCII 32..=95 (uppercase, digits, punctuation).
//! Lowercase letters are drawn as uppercase. Each glyph is 5 pixels wide in an 8-pixel cell.

/// Glyph bitmaps: 64 glyphs x 8 rows, most significant bit is the leftmost pixel.
pub const FONT: [[u8; 8]; 64] = build();

/// Index into [`FONT`] for a character.
pub fn glyph_code(c: char) -> u8 {
    let c = c.to_ascii_uppercase();
    let code = c as u32;
    if (32..96).contains(&code) {
        (code - 32) as u8
    } else {
        b'?' - 32
    }
}

