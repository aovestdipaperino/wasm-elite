const fn build() -> [[u8; 8]; 64] {
    let mut out = [[0u8; 8]; 64];
    let mut g = 0;
    while g < 64 {
        let bytes = ROWS[g].as_bytes();
        let mut row = 0;
        while row < 7 {
            let mut bits = 0u8;
            let mut col = 0;
            while col < 5 {
                let ch = bytes[row * 6 + col];
                if ch == b'#' {
                    bits |= 0x80 >> col;
                }
                col += 1;
            }
            out[g][row] = bits;
            row += 1;
        }
        g += 1;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rows_are_well_formed() {
        for (i, r) in ROWS.iter().enumerate() {
            assert_eq!(r.len(), 41, "glyph {i} has wrong row layout");
        }
        assert_eq!(FONT[glyph_code('A') as usize][0], 0b0111_0000);
        assert_eq!(
            FONT[glyph_code('a') as usize],
            FONT[glyph_code('A') as usize]
        );
        assert_eq!(glyph_code('~'), b'?' - 32);
    }
}
